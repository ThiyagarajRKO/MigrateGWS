#!/usr/bin/env node

/**
 * Generate a verification token for testing user creation
 * This mimics the delegation setup process that normally happens in the UI
 */

import fs from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

/**
 * Generate verification token (mimics the generateVerificationToken function)
 */
function generateVerificationToken(verifiedDomains, adminEmails, migrationScenario, delegationStatus) {
  // Get service account email from environment or use the known one
  const serviceAccountEmail = 
    process.env.NEXT_PUBLIC_GOOGLE_SERVICE_ACCOUNT_CLIENT_EMAIL || 
    process.env.GOOGLE_SERVICE_ACCOUNT_CLIENT_EMAIL || 
    process.env.SERVICE_ACCOUNT_EMAIL ||
    'gws-permission@gws-migration-463208.iam.gserviceaccount.com';

  const tokenData = {
    verificationId: `dwd_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`,
    timestamp: new Date().toISOString(),
    verifiedDomains,
    serviceAccountEmail,
    migrationScenario,
    adminEmails,
    delegationStatus: {
      sourceVerified: delegationStatus.source.verified,
      destVerified: delegationStatus.dest.verified
    },
    apiAuthenticationEnabled: true,
    generatedBy: 'TestTokenGenerator',
    sessionId: `test_session_${Date.now()}`
  };

  // Base64 encode the token data
  return Buffer.from(JSON.stringify(tokenData)).toString('base64');
}

/**
 * Create a test verification token for the migration domains
 */
function createTestVerificationToken() {
  console.log('🔐 Generating verification token for test domains...');
  
  // Test domains from your setup
  const verifiedDomains = ['sample.arakutourism.net', 'migrate.arakutourism.net'];
  const adminEmails = {
    'sample.arakutourism.net': 'admin@sample.arakutourism.net',
    'migrate.arakutourism.net': 'admin@migrate.arakutourism.net'
  };
  
  // Simulate that delegation has been verified
  const delegationStatus = {
    source: { verified: true },
    dest: { verified: true }
  };
  
  const migrationScenario = 'cross-tenant';
  
  const token = generateVerificationToken(verifiedDomains, adminEmails, migrationScenario, delegationStatus);
  
  console.log('✅ Verification token generated:');
  console.log(`   Token length: ${token.length} characters`);
  console.log(`   Verified domains: ${verifiedDomains.join(', ')}`);
  console.log(`   Migration scenario: ${migrationScenario}`);
  console.log(`   Service account: gws-permission@gws-migration-463208.iam.gserviceaccount.com`);
  
  // Parse the token to verify it's valid
  try {
    const decoded = JSON.parse(Buffer.from(token, 'base64').toString());
    console.log('✅ Token validation successful:');
    console.log(`   Verification ID: ${decoded.verificationId}`);
    console.log(`   Generated by: ${decoded.generatedBy}`);
    console.log(`   Timestamp: ${decoded.timestamp}`);
    console.log(`   API Auth Enabled: ${decoded.apiAuthenticationEnabled}`);
  } catch (error) {
    console.error('❌ Token validation failed:', error.message);
    return null;
  }
  
  // Save the token to a file for use in tests
  const tokenData = {
    token,
    verifiedDomains,
    adminEmails,
    migrationScenario,
    delegationStatus,
    generated: new Date().toISOString(),
    usage: 'For testing user creation API with proper delegation verification'
  };
  
  fs.writeFileSync('test-verification-token.json', JSON.stringify(tokenData, null, 2));
  console.log('💾 Token saved to test-verification-token.json');
  
  return token;
}

// Generate the token
const token = createTestVerificationToken();

if (token) {
  console.log('\n🚀 Token ready for use in test scripts!');
  console.log('   Use this token in your user creation API calls to bypass delegation checks.');
} else {
  console.error('❌ Failed to generate verification token');
  process.exit(1);
}
